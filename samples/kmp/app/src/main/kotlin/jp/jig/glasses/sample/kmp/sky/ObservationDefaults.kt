package jp.jig.glasses.sample.kmp.sky

/** 観測画面と方位合わせで共有する、実機確認済みの既定値。 */
object ObservationDefaults {
    /** 測位できないときだけ使う観測地。鯖江 */
    val site = Site(latDeg = 35.9432, lonDeg = 136.1846)

    /** 屋内では測位が返らないことがあるため、待ち続けない。 */
    const val LOCATION_TIMEOUT_MS = 8_000L

    /** 実機に合わせた星図の横画角。パネルそのものの表示画角は未確認。 */
    const val STAR_MAP_FOV_DEG = 35.0

    /** 肉眼と緑8階調の表示で使う恒星の限界等級。 */
    const val LIMIT_MAGNITUDE = 5.0
}

// 観測画面の周期と衛星の絞り込み。既定値と同じく観測の振る舞いの正本

/** 空の暗さを測り直す間隔。薄暮から夜へ移るのは数十分かかる */
const val SKY_DARKNESS_REFRESH_MS = 15_000L

/**
 * 衛星の印を動かす間隔。
 *
 * 天頂を通る衛星は 1 秒に 1°（画面では 15 画素）動く。
 * 1.5 秒ごとなら 20 画素ほどの遅れで、テキストは 1 パケットなので転送も邪魔しない。
 */
const val MARKER_INTERVAL_MS = 1_500L

/**
 * AI へ渡す星座の数。
 *
 * **先頭が主役で、残りは「同じ視野にも入っている」だけ。** 並べるほどモデルが主役を
 * 選び直す余地が増えるので、4 つから減らした（AGENTS.md の「箇条書きを増やすほど薄まる」）。
 */
const val NARRATION_CONSTELLATIONS = 3

/** 一度に重ねる機体の数。**星座の邪魔をしない**ための上限（#36） */
const val MAX_SATELLITES_IN_VIEW = 3

/**
 * 星図に重ねる衛星。**名前で「なにか」が分かるものだけ**に絞る。
 *
 * 名前つき 24 機のうち、だいち・いぶき・しきさい・しずく・テラ・アクア・ランドサット・NOAA は
 * **初心者には名前が手がかりにならない**（見えているのは同じ点なので、名前が読めないと情報が無い）。
 * 測位衛星（GPS・みちびき・ガリレオ）と、名前を知っている ISS・天宮・ひまわり・ハッブルを残す。
 */
val NOTABLE_SATELLITES = listOf("ISS", "天宮", "みちびき", "GPS", "ガリレオ", "ひまわり", "ハッブル")
