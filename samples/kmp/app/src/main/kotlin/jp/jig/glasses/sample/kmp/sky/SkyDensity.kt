package jp.jig.glasses.sample.kmp.sky

/**
 * 空の濃さ。**何等星まで描くか**と**どの星座まで線と名前を出すか**を一緒に決める。
 *
 * **既定は「肉眼でよく見えるものだけ」。** 5 等まで全部描くと、街の明かりの下では
 * **目に見えていない星まで星図に写る**ので、脳が対応を取れず「合っていない」と感じる
 * （見えない星を描かないのは [docs/team-e/14_alignment-accuracy.md] の I）。
 *
 * **かといって絞りすぎるとスカスカになる。** 3 等までにすると視野に 2〜3 個しか残らず、
 * 星座の形が読めない。だから**段階で選べるようにして、既定を「ふつう」に置く**。
 *
 * 星座の間引きは**その星座でいちばん明るい星**で決める。等級の下限を上げるほど、
 * うみへび座やろくぶんぎ座のような暗い星座が落ちて、見て分かる星座だけが残る。
 */
enum class SkyDensity(
    val label: String,
    /** 恒星の限界等級 */
    val limitMagnitude: Double,
    /** 星座の線と名前を出す下限。その星座でいちばん明るい星がこれより暗ければ出さない */
    val constellationMagnitude: Double,
    val hint: String,
) {
    /** 町の明かりの下。1〜2 等星と、誰でも知っている星座だけ */
    TOWN("街の空", 3.4, 2.0, "町の明かりの下で見えるぶんだけ"),

    /** 既定。肉眼でよく見える星と、形が読める星座 */
    STANDARD("ふつう", 4.2, 2.8, "肉眼でよく見える星と星座（既定）"),

    /** 郊外の暗い空 */
    DARK("暗い空", 4.8, 3.6, "郊外。暗い星座も出る"),

    /** 同梱の星表にあるものすべて */
    ALL("全部", 5.0, 99.0, "星表にあるものすべて。街では見えない星も写る"),
    ;

    companion object {
        val default = STANDARD
    }
}
