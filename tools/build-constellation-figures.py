def main() -> int:
    root = Path(__file__).resolve().parent.parent
    out = root / "data" / "constellation-figures.json"
    payload = {
        "note": "手描きの星座絵。正規化 [0,1]（x=右・y=下）で、"
                "星座線の外接矩形へ写して薄く重ねる。向きは南を向いた星図と同じ",
        "count": len(FIGURES),
        "figures": {
            abbr: [[[round(x, 3), round(y, 3)] for x, y in stroke] for stroke in strokes]
            for abbr, strokes in sorted(FIGURES.items())
        },
    }
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    strokes = sum(len(s) for s in FIGURES.values())
    points = sum(len(p) for s in FIGURES.values() for p in s)
    print(f"ok: {out.relative_to(root)} に {len(FIGURES)} 星座・{strokes} ストローク・{points} 点")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
